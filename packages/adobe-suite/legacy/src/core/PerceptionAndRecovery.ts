import { EntityState, IValidationAndRecovery, ValidationResult, Operation } from './abstractions.js';
import { FileSystemObserver } from './FileSystemObserver.js';
import { IVisionModelProvider, MockVisionModelProvider, SpatialVLMResponse } from '../ai/VisionModelProvider.js';

export class PerceptionAndRecoveryLayer implements IValidationAndRecovery {
  private MAX_RETRIES = 3;
  private fsObserver: FileSystemObserver;
  public vlmProvider: IVisionModelProvider;

  constructor() {
    this.fsObserver = new FileSystemObserver();
    this.vlmProvider = new MockVisionModelProvider();
  }

  public validateState<T>(state: EntityState<T>): ValidationResult {
    if (!state.observed) {
      return { isValid: false, divergences: ['Observed state is missing'] };
    }

    // Req 3: Validation of Asset Integrity (Perception Layer Upgrade)
    // If the provider returned explicit layers, we ensure critical structures exist
    if ((state.desired as any).required_layers && (state.observed as any).layers) {
        const requiredLayers: string[] = (state.desired as any).required_layers;
        const observedLayers: string[] = (state.observed as any).layers;
        const missing = requiredLayers.filter(l => !observedLayers.includes(l));

        if (missing.length > 0) {
            state.status = 'diverged';
            return { isValid: false, divergences: [`Missing critical layers: ${missing.join(', ')}`] };
        }
    }

    const isSynced = JSON.stringify(state.desired) === JSON.stringify(state.observed);

    if (isSynced) {
      state.status = 'synchronized';
      return { isValid: true };
    } else {
      state.status = 'diverged';
      return { isValid: false, divergences: ['State properties do not match'] };
    }
  }

  /**
   * Specifically validates physical files generated by operations like exports
   */
  public async validatePhysicalArtifact(filePath: string): Promise<ValidationResult> {
    const isStable = await this.fsObserver.waitForFileStabilization(filePath, 500, 10000, 2);
    if (isStable) {
       return { isValid: true };
    } else {
       return { isValid: false, divergences: [`Artifact ${filePath} failed to stabilize or never appeared`] };
    }
  }


  public async validateVisualArtifact(filePath: string, criteria: string): Promise<ValidationResult> {
    const vlmResult = await this.vlmProvider.inspectImage(filePath, criteria);
    if (vlmResult.isValid) {
        return { isValid: true };
    } else {
        return { isValid: false, divergences: [`Visual validation failed: ${vlmResult.feedback}`] };
    }
  }


  public async validateSpatialArtifact(filePath: string, element: string): Promise<{ isValid: boolean; spatialData?: SpatialVLMResponse; divergences?: string[] }> {
    const vlmResult = await this.vlmProvider.inspectImageSpatial(filePath, element);
    // If it's found but has offsets that aren't 0,0, we consider it diverged spatially
    if (vlmResult.found && (vlmResult.x !== 0 || vlmResult.y !== 0)) {
        return { isValid: false, spatialData: vlmResult, divergences: [`Spatial misalignment detected for ${element}: ${vlmResult.feedback}`] };
    }
    return { isValid: true };
  }

  public async attemptRecovery(operationId: string, engineExecuteCallback: (opId: string) => Promise<Operation>): Promise<boolean> {
    console.log(`[Recovery] Attempting recovery for operation: ${operationId}`);

    let attempts = 0;
    while (attempts < this.MAX_RETRIES) {
      try {
        const recoveredOp = await engineExecuteCallback(operationId);

        if (recoveredOp.status === 'SUCCESS') {
          console.log(`[Recovery] Successfully recovered operation: ${operationId} on attempt ${attempts + 1}`);
          return true;
        }

        console.warn(`[Recovery] Attempt ${attempts + 1} failed for operation: ${operationId}`);
      } catch (error) {
        console.error(`[Recovery] Error during recovery of ${operationId} on attempt ${attempts + 1}:`, error);
      }

      attempts++;
    }

    console.error(`[Recovery] Max retries (${this.MAX_RETRIES}) reached for operation: ${operationId}. Aborting.`);
    return false;
  }
}
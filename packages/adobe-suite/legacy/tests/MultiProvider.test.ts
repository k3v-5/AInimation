import { test, expect, describe } from 'vitest';
import { AnimationEngine } from '../src/core/AnimationEngine.js';
import { IAnimationProvider, CapabilityDefinition, CapabilityId } from '../src/core/abstractions.js';

class MockCharacterProvider implements IAnimationProvider {
  id = 'character_animator';
  capabilities(): CapabilityDefinition[] { return [{ id: 'render.export', inputSchema: {}, outputSchema: {}, supports: 'sync', reversibility: 'reversible', observability: 'full' }]; }
  async connect() {}
  async disconnect() {}
  async executeCapability(capabilityId: CapabilityId, input: Record<string, any>): Promise<any> {
    return { success: true };
  }
}

class MockAfterEffectsProvider implements IAnimationProvider {
  id = 'after_effects';
  public lastInput: any = null;
  capabilities(): CapabilityDefinition[] { return [{ id: 'ae.render.export', inputSchema: {}, outputSchema: {}, supports: 'sync', reversibility: 'reversible', observability: 'full' }]; }
  async connect() {}
  async disconnect() {}
  async executeCapability(capabilityId: CapabilityId, input: Record<string, any>): Promise<any> {
    this.lastInput = input;
    return { success: true };
  }
}

describe('Multi-Provider Orchestration and Context Passing', () => {
  test('Resolves context variables between DAG nodes across providers', async () => {
    const engine = new AnimationEngine();
    const chProvider = new MockCharacterProvider();
    const aeProvider = new MockAfterEffectsProvider();

    engine.registerProvider(chProvider);
    engine.registerProvider(aeProvider);

    const intent = {
      id: 'multi_app_intent',
      type: 'animation.sequence',
      parameters: {
        scene: { name: 'Test Scene' },
        characters: [{ id: 'char_1', asset_path: 'path' }],
        actions: [
          { type: 'render', provider: 'character_animator' },
          // This node explicitly targets After Effects and references the artifact generated by the previous render node
          { type: 'ae_render', provider: 'after_effects', input_file: '${action_render_0.output}' }
        ]
      }
    };

    const result = await engine.processIntent(intent, 'character_animator');
    expect(result.status).toBe('SUCCESS');

    // Check if the AE provider actually received the resolved context path instead of the literal string
    expect(aeProvider.lastInput).toBeDefined();

    expect(aeProvider.lastInput.input_file).toContain('Artifacts'); // Should be a resolved local path
  });
});

import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import { AnimationEngine } from '../src/core/AnimationEngine.js';
import { Intent, Capability, Provider, Plan, Operation } from '../src/core/abstractions.js';
import { WorkflowGraphEngine } from '../src/core/WorkflowGraphEngine.js';
import fs from 'fs';
import { db } from '../src/core/Database.js';
import * as hashUtils from '../src/core/utils/hash.js';

describe('Cache-Aware DAG Execution', () => {
  let engine: AnimationEngine;

  beforeEach(() => {
    engine = new AnimationEngine();
    db.exec('DELETE FROM assets');
    db.exec('DELETE FROM projects');
    vi.spyOn(fs, 'existsSync').mockImplementation((path) => {
      if (typeof path === 'string' && path.includes('cached_file.psd')) {
        return true;
      }
      return false;
    });
    vi.spyOn(hashUtils, 'calculateFileHash').mockReturnValue('mocked_hash_value');
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  it('should skip execution for ps.document.create if input_file exists on disk', async () => {
    // Create a mock provider
    class MockPsProvider implements Provider {
      id = 'mock-ps';
      name = 'Mock Photoshop';
      supportedCapabilities = ['ps.document.create' as Capability];

      async executeCapability(capability: Capability, parameters: Record<string, any>) {
        return {
          success: true,
          observed_state: {
            executed: true,
            created_file: parameters.input_file
          }
        };
      }
    }

    engine.registerProvider(new MockPsProvider());

    const plan: Plan = {
      operations: [
        {
          id: 'op1',
          capability: 'ps.document.create' as Capability,
          input: {
            input_file: '/path/to/cached_file.psd',
            prompt: 'a dog'
          },
          dependencies: []
        }
      ]
    };

    let executedCount = 0;

    // Mock provider execution to track if it is called
    vi.spyOn(engine, 'getProvider').mockImplementation((id) => {
       const prov = engine['providers'].get(id);
       if (prov) {
         vi.spyOn(prov, 'executeCapability').mockImplementation(async () => {
            executedCount++;
            return { success: true };
         });
       }
       return prov;
    });

    const activeProjectId = "proj_test_123";

    // Inject matching hash into DB to prevent Dirty State invalidation
    const pm = engine['projectManager'];
    const p = pm.createProject('Test Project'); // Ensure a project exists
    pm.saveAsset({
       id: 'test_asset_123',
       project_id: p.id,
       type: 'puppet',
       local_path: '/path/to/cached_file.psd',
       hash: 'mocked_hash_value',
       created_at: new Date().toISOString()
    });
    // We pass an intent directly since engine uses processIntent
    const intent = {
      id: "intent_123",
      type: "create",
      parameters: {
        asset_type: "puppet",
        target_path: "/path/to/cached_file.psd"
      }
    };

    // Override parser
    vi.spyOn(engine['intentParser'], 'parse').mockReturnValue({
      nodes: [
        {
          id: 'op1',
          capability: 'ps.document.create',
          inputs: [],
          outputs: [],
          constraints: [{ provider: 'mock-ps', parameters: { input_file: '/path/to/cached_file.psd', prompt: 'a dog' } }]
        }
      ],
      edges: []
    });

    vi.spyOn(engine['workflowEngine'], 'resolveExecutionOrder').mockReturnValue([
      [ {
          id: 'op1',
          capability: 'ps.document.create',
          inputs: [],
          outputs: [],
          constraints: [{ provider: 'mock-ps', parameters: { input_file: '/path/to/cached_file.psd', prompt: 'a dog' } }]
        } ]
    ]);

    const runResult = await engine.processIntent(intent, 'mock-ps');

    expect(runResult.status).toBe("SUCCESS");
    // Provider execute capability should not have been called because it was cached
    expect(executedCount).toBe(0);

    // Check if output artifacts were logged as SKIPPED and saved with cached path
    const assets = db.prepare('SELECT * FROM assets').all();
    // We expect 2 assets now: the mocked database hit and the JSON artifact generated by processIntent
    expect(assets.length).toBe(2);
    // The asset saved in DB is the artifact JSON path (ArtifactManager default behavior),
    // but the engine output artifacts array should contain the true cached path.
    expect(runResult.artifacts[0].local_path).toBe('/path/to/cached_file.psd');
  });
});
